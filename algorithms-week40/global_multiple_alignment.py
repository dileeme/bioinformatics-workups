def pairwise_align(s, t, gap=-8):
    n, m = len(s), len(t)
    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        dp[i][0] = dp[i - 1][0] + gap
    for j in range(1, m + 1):
        dp[0][j] = dp[0][j - 1] + gap
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            dp[i][j] = max(
                dp[i - 1][j - 1] + BLOSUM62[s[i - 1]][t[j - 1]],
                dp[i - 1][j] + gap,
                dp[i][j - 1] + gap,
            )
    aligned_s, aligned_t = [], []
    i, j = n, m
    while i > 0 and j > 0:
        if dp[i][j] == dp[i - 1][j - 1] + BLOSUM62[s[i - 1]][t[j - 1]]:
            aligned_s.append(s[i - 1])
            aligned_t.append(t[j - 1])
            i -= 1
            j -= 1
        elif dp[i][j] == dp[i - 1][j] + gap:
            aligned_s.append(s[i - 1])
            aligned_t.append("-")
            i -= 1
        else:
            aligned_s.append("-")
            aligned_t.append(t[j - 1])
            j -= 1
    while i > 0:
        aligned_s.append(s[i - 1])
        aligned_t.append("-")
        i -= 1
    while j > 0:
        aligned_s.append("-")
        aligned_t.append(t[j - 1])
        j -= 1
    return "".join(reversed(aligned_s)), "".join(reversed(aligned_t))

def column_score(column, residue, gap=-8):
    total = 0
    for c in column:
        if c == "-" or residue == "-":
            total += gap
        else:
            total += BLOSUM62[c][residue]
    return total

def add_sequence_to_profile(rows, seq, gap=-8):
    n = len(rows[0])
    k = len(rows)
    m = len(seq)
    columns = [[row[i] for row in rows] for i in range(n)]

    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        dp[i][0] = dp[i - 1][0] + column_score(columns[i - 1], "-", gap)
    for j in range(1, m + 1):
        dp[0][j] = dp[0][j - 1] + gap * k
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            diag = dp[i - 1][j - 1] + column_score(columns[i - 1], seq[j - 1], gap)
            up = dp[i - 1][j] + column_score(columns[i - 1], "-", gap)
            left = dp[i][j - 1] + gap * k
            dp[i][j] = max(diag, up, left)

    ops = []
    i, j = n, m
    while i > 0 and j > 0:
        diag = dp[i - 1][j - 1] + column_score(columns[i - 1], seq[j - 1], gap)
        up = dp[i - 1][j] + column_score(columns[i - 1], "-", gap)
        if dp[i][j] == diag:
            ops.append(("match", i - 1, j - 1))
            i -= 1
            j -= 1
        elif dp[i][j] == up:
            ops.append(("up", i - 1, None))
            i -= 1
        else:
            ops.append(("left", None, j - 1))
            j -= 1
    while i > 0:
        ops.append(("up", i - 1, None))
        i -= 1
    while j > 0:
        ops.append(("left", None, j - 1))
        j -= 1
    ops.reverse()

    new_rows = [[] for _ in range(k)]
    new_seq_row = []
    for op, ci, sj in ops:
        if op == "match":
            for r in range(k):
                new_rows[r].append(columns[ci][r])
            new_seq_row.append(seq[sj])
        elif op == "up":
            for r in range(k):
                new_rows[r].append(columns[ci][r])
            new_seq_row.append("-")
        else:
            for r in range(k):
                new_rows[r].append("-")
            new_seq_row.append(seq[sj])

    result_rows = ["".join(r) for r in new_rows]
    result_rows.append("".join(new_seq_row))
    return result_rows

def progressive_alignment(sequences, gap=-8):
    rows = list(pairwise_align(sequences[0], sequences[1], gap))
    for seq in sequences[2:]:
        rows = add_sequence_to_profile(rows, seq, gap)
    return rows

def sum_of_pairs_score(rows, gap=-8):
    k = len(rows)
    n = len(rows[0])
    total = 0
    for col in range(n):
        chars = [row[col] for row in rows]
        for a in range(k):
            for b in range(a + 1, k):
                x, y = chars[a], chars[b]
                if x == "-" or y == "-":
                    total += gap
                else:
                    total += BLOSUM62[x][y]
    return total

