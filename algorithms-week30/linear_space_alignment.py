INDEL_PENALTY = 5

def last_column_scores(s, t):
    n = len(s)
    prev = [-INDEL_PENALTY * i for i in range(n + 1)]
    for char in t:
        cur = [0] * (n + 1)
        cur[0] = prev[0] - INDEL_PENALTY
        for i in range(1, n + 1):
            cur[i] = max(prev[i - 1] + BLOSUM62[s[i - 1]][char], prev[i] - INDEL_PENALTY, cur[i - 1] - INDEL_PENALTY)
        prev = cur
    return prev

def middle_node_and_edge(s, t):
    m = len(t)
    mid = m // 2
    forward = last_column_scores(s, t[:mid])
    backward = last_column_scores(s[::-1], t[mid:][::-1])[::-1]
    scores = [f + b for f, b in zip(forward, backward)]
    best_i = max(range(len(scores)), key=lambda i: scores[i])

    if mid == m:
        return best_i, mid, best_i, mid

    forward_next = last_column_scores(s, t[:mid + 1])
    backward_next = last_column_scores(s[::-1], t[mid + 1:][::-1])[::-1]

    best_score = None
    best_edge = None
    n = len(s)
    for i in range(n + 1):
        if i < n:
            total = forward[i] + BLOSUM62[s[i]][t[mid]] + backward_next[i + 1]
            if best_score is None or total > best_score:
                best_score, best_edge = total, (i, mid, i + 1, mid + 1)
        total = forward[i] - INDEL_PENALTY + backward_next[i]
        if best_score is None or total > best_score:
            best_score, best_edge = total, (i, mid, i, mid + 1)
        if i < n:
            total = forward[i] - INDEL_PENALTY + backward[i + 1]
            if best_score is None or total > best_score:
                best_score, best_edge = total, (i, mid, i + 1, mid)

    return best_edge

def linear_space_alignment(s, t):
    if len(s) == 0:
        return "-" * len(t), t
    if len(t) == 0:
        return s, "-" * len(s)
    if len(s) == 1 or len(t) == 1:
        return small_alignment(s, t)

    i1, j1, i2, j2 = middle_node_and_edge(s, t)

    left_s, left_t = linear_space_alignment(s[:i1], t[:j1])

    if i2 == i1 + 1 and j2 == j1 + 1:
        mid_s, mid_t = s[i1], t[j1]
    elif i2 == i1 + 1:
        mid_s, mid_t = s[i1], "-"
    else:
        mid_s, mid_t = "-", t[j1]

    right_s, right_t = linear_space_alignment(s[i2:], t[j2:])

    return left_s + mid_s + right_s, left_t + mid_t + right_t

def small_alignment(s, t):
    n, m = len(s), len(t)
    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n + 1):
        dp[i][0] = -INDEL_PENALTY * i
    for j in range(m + 1):
        dp[0][j] = -INDEL_PENALTY * j
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            dp[i][j] = max(
                dp[i - 1][j - 1] + BLOSUM62[s[i - 1]][t[j - 1]],
                dp[i - 1][j] - INDEL_PENALTY,
                dp[i][j - 1] - INDEL_PENALTY,
            )

    aligned_s, aligned_t = [], []
    i, j = n, m
    while i > 0 or j > 0:
        if i > 0 and j > 0 and dp[i][j] == dp[i - 1][j - 1] + BLOSUM62[s[i - 1]][t[j - 1]]:
            aligned_s.append(s[i - 1])
            aligned_t.append(t[j - 1])
            i -= 1
            j -= 1
        elif i > 0 and dp[i][j] == dp[i - 1][j] - INDEL_PENALTY:
            aligned_s.append(s[i - 1])
            aligned_t.append("-")
            i -= 1
        else:
            aligned_s.append("-")
            aligned_t.append(t[j - 1])
            j -= 1

    return "".join(reversed(aligned_s)), "".join(reversed(aligned_t))

def alignment_score(aligned_s, aligned_t):
    score = 0
    for a, b in zip(aligned_s, aligned_t):
        if a == "-" or b == "-":
            score -= INDEL_PENALTY
        else:
            score += BLOSUM62[a][b]
    return score

